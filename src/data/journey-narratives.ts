/**
 * 将四段叙事片段拼接为完整的人格旅程故事
 *
 * @param openingGuide  - 第一章主导星灵 ID（决定开场）
 * @param midpointKey   - 第三章前两位星灵组合键（如 "flame_forest"）
 * @param climaxKey     - 第四章人格武装星灵组合键（如 "flame_forest"）
 * @param endingComboId - 最终星灵组合 ID（如 "dual_flame_forest"）
 * @returns 完整旅程故事文本
 */
export function assembleJourneyStory(
  openingGuide: GuideId,
  midpointKey: string,
  climaxKey: string,
  endingComboId: string,
): string {
  const opening = journeyOpenings[openingGuide] ?? journeyOpenings['flame']
  const midpoint = journeyMidpoints[midpointKey] ?? journeyMidpoints['flame_forest']
  const climax = journeyClimaxes[climaxKey] ?? journeyClimaxes['flame_forest']
  const ending = journeyEndings[endingComboId] ?? journeyEndings['single_flame']

  return [opening, midpoint, climax, ending].join('\n\n')
}
